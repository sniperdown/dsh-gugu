/**
 * 出站纯文本整形：把 Markdown 剥成 **QQ 能看的纯文本**。
 *
 * ## 为什么需要它
 *
 * QQ **不渲染** Markdown。`**粗体**`、`# 标题`、表格竖线都会**原样显示**，
 * 看着像乱码。而模型（小鲸鱼、别的会话、子会话）默认都按 Markdown 写。
 *
 * 用户 2026-10-08 原话：「你送到 qq 这边的文字得做个变化，**把你文本里的 md 格式通通去掉**」。
 *
 * 这一层在旧插件 `dsh-onebot-qq` 里**本来有**（`lib/split.js` 的 `stripMarkdown`，
 * `lib/outbound.js` 调用它），重写成 qq-proactive 时**没带过来** —— 这里补上。
 *
 * ## 与 `rich.mjs` 是一对
 *
 * | 模块 | 方向 | 干什么 |
 * |---|---|---|
 * | `rich.mjs` | **入站** | 富段（合并转发/卡片）→ 模型能读的文本 |
 * | 本模块 | **出站** | 模型写的 Markdown → QQ 能看的纯文本 |
 *
 * ## 三条不变量（每条都有测试钉住）
 *
 * 1. **没有 MD 就逐字节不变** —— 所有剥离规则都以 MD 触发字符为条件，
 *    而收尾的空行/行尾空格整理**只在真的剥掉过东西时才做**。
 *    所以一段纯文本（哪怕行尾带空格、带三个空行）进来什么样、出去什么样。
 * 2. **剥格式，不剥内容** —— 代码（围栏/行内）与链接 URL 先"存起来"再剥外层，
 *    存起来的东西**一个字节都不动**。
 * 3. **列点不剥** —— `1. ` / `- ` / `· ` 是**纯文本风格**（人格里明确要求的说话方式），
 *    不是 Markdown 语法，QQ 上照样好读。
 *
 * ## 刻意**不**收的东西（判不准就不动）
 *
 * | 形状 | 为什么不动 |
 * |---|---|
 * | `\*字面星号\*` | 反斜杠转义：星号是**内容**。原样留着（连反斜杠一起）。 |
 * | `2 * 3 * 4` | 两侧空白的 `*` 不是强调（CommonMark 的 flanking 规则），是乘号/间隔符。 |
 * | `__init__` | 双下划线包一个 ASCII 标识符 ⇒ 那是**名字**，不是粗体。 |
 * | `issue # 12` | `#` 不在行首 ⇒ 不是标题。 |
 * | `a \| b 只是并排` | 没被竖线包住的整行 ⇒ 不是表格，正文里的 `\|` 一个都不动。 |
 * | `** 不是粗体 **` | 内侧是空白 ⇒ 不是强调。 |
 *
 * @module qq-onebot/plain-text
 */

/** 反斜杠转义：`\` + ASCII 标点（`\*` `\_` `` \` `` `\#` `\[` …）。 */
const ESCAPED = /\\([\u0021-\u002F\u003A-\u0040\u005B-\u0060\u007B-\u007E])/g;

/**
 * 把 Markdown 剥成 QQ 能看的纯文本。
 *
 * @param {unknown} input 模型产出的文本（非字符串一律按 `String(...)` 处理）
 * @returns {string} 可以直接发给 QQ 的纯文本；空正文/纯空白**原样返回**
 */
export function stripMarkdown(input) {
  const start = typeof input === 'string' ? input : String(input ?? '');
  // 空正文 / 纯空白：原样（QQ 上本来就什么都不显示，剥了也没意义）。
  if (start.trim() === '') return start;

  // 占位符前缀：挑一个输入里**绝对没有**的 —— 免得把用户内容里的 NUL 当成占位符还原。
  let nonce = '\u0000';
  while (start.includes(nonce)) nonce += '\u0000';

  /**
   * "先存起来"的表：文本里换成 `\u0000<下标>\u0000`，最后逐条放回。
   *
   * 这是"剥格式不剥内容"的实现方式：代码和 URL 一旦进了这张表，
   * 后面的每一条剥离规则都**看不见**它们，也就伤不到它们。
   */
  const stash = [];
  const keep = (text) => {
    stash.push(text);
    return `${nonce}${stash.length - 1}${nonce}`;
  };

  let t = start;

  // ① 代码围栏：干掉围栏行，**里面的代码先存起来**。
  //    ⚠️ 与 `send-qq.mjs` 的差别之一：那边是把内容放回文本流，于是代码里的
  //    `` ` `` 和 `**` 会被后面的规则继续剥（`x = a ** b` 会变样），
  //    与"代码块保留代码"冲突。
  t = t.replace(/^[ \t]*```[^\n]*\n([\s\S]*?)^[ \t]*```[ \t]*$/gm, (_m, body) => keep(body.replace(/\n$/, '')));
  // 落单的围栏行（后面只有语言名/空白）：整行删掉。
  // **只删"整行就是围栏"的** —— 行里还有别的字就不动它（宁可留着反引号，也不静默删掉内容）。
  t = t.replace(/^[ \t]*`{3,}[ \t]*[^\s`]*[ \t]*\r?\n?/gm, '');

  // ② 行内代码：同样先存起来 —— `` `**x**` `` 里的 `**` 是**内容**，不是粗体。
  t = t.replace(/`([^`\n]+)`/g, (_m, body) => keep(body));

  // ③ 转义字符：`\*` 的星号是字面内容，先存起来免得被当强调符吃掉。
  //    （不剥掉那个反斜杠 —— 宁可少剥，不可多剥。）
  t = t.replace(ESCAPED, (_m, ch) => keep(`\\${ch}`));

  // ④ 链接 / 图片：保留文字 + URL（QQ 里链接要能点、能复制）。
  //    ⚠️ 与 `send-qq.mjs` 的差别之二：**放在强调之前**，且 **URL 单独存起来**。
  //    否则 `https://x.com/__init__` 会先被强调规则吃成 `https://x.com/init`。
  t = t.replace(/!\[([^\]\n]*)\]\((https?:\/\/[^)\s]+)\)/g, (_m, text, url) => `${text} ${keep(url)}`);
  t = t.replace(/\[([^\]\n]*)\]\((https?:\/\/[^)\s]+)\)/g, (_m, text, url) => `${text} ${keep(url)}`);

  // ⑤ 粗体 / 斜体 / 删除线。
  //    · 内侧**必须非空**（`+?`）—— 否则 `** 不是粗体 **` 里的那对 `**`
  //      会被当成一对"空强调"整个吃掉（实测踩到过）。
  //    · 加"两侧不能是空白"的定界条件（CommonMark 的 flanking）——
  //      `2 * 3 * 4` 是乘号，不是斜体。
  t = t.replace(/\*\*(?![\s*])([^*\n]+?)(?<![\s*])\*\*/g, '$1');
  t = t.replace(/~~([^~\n]+)~~/g, '$1');
  t = t.replace(/(^|[^\w*])\*(?!\s)([^*\n]+?)(?<!\s)\*(?![\w*])/g, '$1$2');
  //    ⚠️ 与 `send-qq.mjs` 的差别之三：`__x__` **只在"内侧不像代码标识符"时**才当粗体剥。
  //    `__init__` / `__main__` 是**名字**；判不准就一个字不动
  //    （同 `rich.mjs` 里剥 URL 追踪参数那条：认不出的键一律不动）。
  t = t.replace(/(^|[^\w_])__(?!\s)([^_\n]+?)(?<!\s)__(?![\w_])/g,
    (m, pre, inner) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(inner) ? m : pre + inner));
  t = t.replace(/(^|[^\w_])_(?!\s)([^_\n]+?)(?<!\s)_(?![\w_])/g, '$1$2');

  // ⑥ 标题 / 引用
  t = t.replace(/^[ \t]*#{1,6}[ \t]+/gm, '');
  t = t.replace(/^[ \t]*>[ \t]?/gm, '');

  // ⑦ 表格：**逐行**处理，只动"整行被竖线包住"的（正文里的 `|` 一个都不碰）。
  //    分隔行（`|---|---|`）**整行丢掉** —— 它只有格式没有内容，
  //    留一个空行在表格中间很难看（`send-qq.mjs` 会留一个空行）。
  t = t.split('\n').map((line) => {
    if (!/^[ \t]*\|.*\|[ \t]*\r?$/.test(line)) return line;
    const cells = line
      .replace(/^[ \t]*\|/, '')
      .replace(/\|[ \t]*\r?$/, '')
      .split('|')
      .map((cell) => cell.trim());
    const kept = cells.filter((cell) => cell !== '' && !/^:?-{2,}:?$/.test(cell));
    return kept.length === 0 ? null : kept.join('  ·  ');
  }).filter((line) => line !== null).join('\n');
  // 没有外框竖线的分隔行（`---|---`）也整行丢掉
  t = t.replace(/^[ \t]*\|?[ \t:|-]*-{3,}[ \t:|-]*\|?[ \t]*\r?\n?/gm, '');

  // ⑧ 水平线 --- / *** / ___ → 整行删
  t = t.replace(/^[ \t]*([-*_])[ \t]*\1[ \t]*\1[\s\S]*?$/gm, '');

  // ⑨ 安全网：还剩落单的三连反引号就删掉（真代码已经存起来了，碰不到）
  t = t.replace(/`{3,}/g, '');

  // ⑩ **只有真剥掉过东西**才整理空行/行尾空格。
  //    这一句就是"纯文本逐字节不变"的关键：没剥过 → 原样返回，一个字节都不动。
  if (t === start) return start;
  t = t.replace(/[ \t]+$/gm, '');
  t = t.replace(/\n{3,}/g, '\n\n');
  t = t.trim();

  // ⑪ 还原存起来的内容。占位符**可能嵌套**（比如围栏代码里含 `\*`），所以要循环展开。
  const re = new RegExp(`${nonce}(\\d+)${nonce}`, 'g');
  for (let i = 0; i < 16; i += 1) {
    const before = t;
    t = t.replace(re, (_m, n) => stash[Number(n)] ?? '');
    if (t === before) break;
  }
  return t;
}
